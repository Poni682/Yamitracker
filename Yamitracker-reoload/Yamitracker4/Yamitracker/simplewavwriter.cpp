QString SimpleWavWriter::generatePentlyPattern(int track, int patternIndex)
{
    // Group events by time to create pattern
    QVector<QVector<WavEvent>> groups = groupEventsByTime(track, 1.0);
    
    if (patternIndex >= groups.size()) {
        return QString();
    }
    
    QString patternData;
    const QVector<WavEvent>& events = groups[patternIndex];
    
    // Add notes to pattern
    for (const auto& event : events) {
        if (!event.isPause) {
            QString noteName = noteNumberToName(event.note);
            QString duration = getDurationSymbol(event.duration);
            patternData += QString("  .byt N_%1|D_%2\n").arg(noteName).arg(duration);
        } else {
            // Pause
            QString duration = getDurationSymbol(event.duration);
            patternData += QString("  .byt REST|D_%1\n").arg(duration);
        }
    }
    
    return patternData;
}

QString SimpleWavWriter::generatePentlySong()
{
    QString songData;
    
    songData += "PSDAT_composition:\n";
    songData += "  setTempo 300\n\n";
    
    // For each track add patterns
    int patternCounter = 0;
    for (int track = 0; track < MAX_TRACKS; track++) {
        if (m_tracks[track].events.isEmpty()) continue;
        
        QVector<QVector<WavEvent>> groups = groupEventsByTime(track, 1.0);
        QString instrumentName = getInstrumentMacroName(m_tracks[track].instrument);
        
        for (int i = 0; i < groups.size(); i++) {
            songData += QString("  playPat %1, %2, 0, %3\n")
                           .arg(track)
                           .arg(patternCounter)
                           .arg(instrumentName);
            patternCounter++;
        }
        
        if (track < MAX_TRACKS - 1 && !m_tracks[track + 1].events.isEmpty()) {
            songData += "  waitRows 16\n";
        }
    }
    
    songData += "\n  waitRows 32\n";
    songData += "  fine\n";
    
    return songData;
}

QVector<QVector<WavEvent>> SimpleWavWriter::groupEventsByTime(int track, double timeThreshold)
{
    QVector<QVector<WavEvent>> groups;
    
    if (track < 0 || track >= MAX_TRACKS || m_tracks[track].events.isEmpty()) {
        return groups;
    }
    
    QVector<WavEvent> currentGroup;
    double lastTime = -timeThreshold * 2; // So first event always starts new group
    
    for (const auto& event : m_tracks[track].events) {
        if (event.time - lastTime > timeThreshold && !currentGroup.isEmpty()) {
            groups.append(currentGroup);
            currentGroup.clear();
        }
        
        currentGroup.append(event);
        lastTime = event.time;
    }
    
    if (!currentGroup.isEmpty()) {
        groups.append(currentGroup);
    }
    
    return groups;
}

QString SimpleWavWriter::getNoteCommand(const WavEvent &event, bool includeInstrument)
{
    if (event.isPause) {
        QString duration = getDurationSymbol(event.duration);
        return QString("REST|D_%1").arg(duration);
    }
    
    QString noteName = noteNumberToName(event.note);
    QString duration = getDurationSymbol(event.duration);
    
    if (includeInstrument) {
        QString instrumentName = getInstrumentMacroName(event.instrument);
        return QString("INSTRUMENT, %1, N_%2|D_%3").arg(instrumentName).arg(noteName).arg(duration);
    } else {
        return QString("N_%1|D_%2").arg(noteName).arg(duration);
    }
}

bool SimpleWavWriter::decodeWavData(const QByteArray &wavData, QVector<int16_t> &samples, int &sampleRate)
{
    // Simplified WAV decoding (only 16-bit mono)
    if (wavData.size() < 44) return false; // Minimum WAV header size
    
    // Check RIFF header
    if (wavData.mid(0, 4) != "RIFF") return false;
    if (wavData.mid(8, 4) != "WAVE") return false;
    
    // Find fmt chunk
    int offset = 12;
    while (offset < wavData.size() - 8) {
        QString chunkId = QString::fromLatin1(wavData.mid(offset, 4));
        int chunkSize = *(int*)(wavData.constData() + offset + 4);
        
        if (chunkId == "fmt ") {
            // Read parameters
            int audioFormat = *(short*)(wavData.constData() + offset + 8);
            if (audioFormat != 1) return false; // Only PCM
            
            int channels = *(short*)(wavData.constData() + offset + 10);
            sampleRate = *(int*)(wavData.constData() + offset + 12);
            int bitsPerSample = *(short*)(wavData.constData() + offset + 22);
            
            if (channels != 1 || bitsPerSample != 16) {
                qDebug() << "Only 16-bit mono WAV files are supported";
                return false;
            }
        } else if (chunkId == "data") {
            // Read audio data
            int dataSize = chunkSize;
            int dataOffset = offset + 8;
            
            if (dataOffset + dataSize > wavData.size()) {
                return false;
            }
            
            samples.resize(dataSize / 2); // 16-bit = 2 bytes per sample
            
            const char* data = wavData.constData() + dataOffset;
            for (int i = 0; i < samples.size(); i++) {
                samples[i] = *(int16_t*)(data + i * 2);
            }
            
            return true;
        }
        
        offset += 8 + chunkSize;
    }
    
    return false;
}

bool SimpleWavWriter::loadWavFile(const QString &filename, QVector<int16_t> &samples, int &sampleRate)
{
    QFile file(filename);
    if (!file.open(QIODevice::ReadOnly)) {
        qDebug() << "Cannot open WAV file:" << filename;
        return false;
    }
    
    QByteArray wavData = file.readAll();
    file.close();
    
    return decodeWavData(wavData, samples, sampleRate);
}

short SimpleWavWriter::generateWaveform(double time, double frequency, double amplitude, int instrument)
{
    double phase = fmod(time * frequency, 1.0);
    double value = 0.0;
    
    WaveformType waveform = getWaveformForInstrument(instrument);
    
    switch (waveform) {
    case WAVEFORM_SINE:
        value = sineWave(phase);
        break;
    case WAVEFORM_SQUARE:
        value = squareWave(phase);
        // Add some harmonics for square wave
        for (int i = 3; i <= 9; i += 2) {
            value += 0.7 / i * sin(2.0 * M_PI * frequency * i * time);
        }
        break;
    case WAVEFORM_SAWTOOTH:
        value = sawtoothWave(phase);
        // Add harmonics for sawtooth wave
        for (int i = 2; i <= 10; i++) {
            value += 0.5 / i * sin(2.0 * M_PI * frequency * i * time);
        }
        break;
    case WAVEFORM_TRIANGLE:
        value = triangleWave(phase);
        // Add odd harmonics for triangle wave
        for (int i = 3; i <= 9; i += 2) {
            value += 0.8 / (i * i) * sin(2.0 * M_PI * frequency * i * time);
        }
        break;
    case WAVEFORM_NOISE:
        value = noiseWave();
        break;
    }
    
    // Apply filter based on instrument
    static double prevLP = 0;
    static double prevHPInput = 0;
    static double prevHPOutput = 0;
    
    double cutoff = getFilterCutoffForInstrument(instrument);
    
    if (instrument >= 28 && instrument <= 40) {
        // Bass - strong low-pass filter
        value = lowPassFilter(value, prevLP, cutoff);
    } else if (instrument == 3 || instrument == 6) {
        // Harpsichord - some high-pass for brightness
        value = highPassFilter(value, prevHPInput, prevHPOutput, 500.0);
    }
    
    // Limit value to avoid clipping
    if (value > 1.0) value = 1.0;
    if (value < -1.0) value = -1.0;
    
    return static_cast<short>(value * amplitude * 32767.0);
}

