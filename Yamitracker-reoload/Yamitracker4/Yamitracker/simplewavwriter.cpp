SimpleWavWriter::SimpleWavWriter(QObject *parent)
    : QObject(parent)
    , m_isRecording(false)
    , m_isPaused(false)
    , m_startTime(0)
    , m_pauseTime(0)
    , m_sampleRate(16000)
    , m_bassVolumeMultiplier(2.0)
    , m_playbackSpeed(1.0)
    , m_masterVolume(1.0)
{
    std::srand(std::time(nullptr));
    
    // Инициализируем дорожки (теперь 7 дорожек)
    m_tracks.resize(MAX_TRACKS);
    for (int i = 0; i < MAX_TRACKS; i++) {
        m_tracks[i].name = QString("Track %1").arg(i + 1);
        m_tracks[i].instrument = 0;
        m_tracks[i].volume = 1.0;
        m_tracks[i].muted = false;
    }
}

SimpleWavWriter::~SimpleWavWriter()
{
}

bool SimpleWavWriter::startRecording(int sampleRate)
{
    if (m_isRecording) {
        stopRecording();
    }
    
    // Очищаем все дорожки
    clearAllTracks();
    
    m_isRecording = true;
    m_isPaused = false;
    m_startTime = QDateTime::currentMSecsSinceEpoch() / 1000.0;
    m_pauseTime = 0;
    m_sampleRate = sampleRate;
    
    qDebug() << "Started recording, sample rate:" << m_sampleRate;
    return true;
}

bool SimpleWavWriter::pauseRecording()
{
    if (!m_isRecording || m_isPaused) {
        return false;
    }
    
    m_isPaused = true;
    m_pauseTime = QDateTime::currentMSecsSinceEpoch() / 1000.0;
    qDebug() << "Recording paused";
    return true;
}

bool SimpleWavWriter::resumeRecording()
{
    if (!m_isRecording || !m_isPaused) {
        return false;
    }
    
    // Корректируем время начала для новых событий
    double pauseDuration = (QDateTime::currentMSecsSinceEpoch() / 1000.0) - m_pauseTime;
    m_startTime += pauseDuration;
    
    m_isPaused = false;
    qDebug() << "Recording resumed, pause duration:" << pauseDuration;
    return true;
}

bool SimpleWavWriter::stopRecording()
{
    if (!m_isRecording) {
        return false;
    }
    
    m_isRecording = false;
    m_isPaused = false;
    
    // Генерируем аудиоданные для быстрого воспроизведения
    generateAllTracksAudio();
    
    qDebug() << "Stopped recording";
    qDebug() << "Track information:";
    for (int i = 0; i < MAX_TRACKS; i++) {
        if (!m_tracks[i].events.isEmpty()) {
            qDebug() << "  Track" << i << ":" << m_tracks[i].name 
                     << ", events:" << m_tracks[i].events.size()
                     << ", duration:" << getTrackDuration(i) << "seconds";
        }
    }
    
    return true;
}

bool SimpleWavWriter::saveToFile(const QString &filename)
{
    QByteArray audioData = getMergedAudioData();
    if (audioData.isEmpty()) {
        qDebug() << "No audio data to save";
        return false;
    }
    
    QFile file(filename);
    if (!file.open(QIODevice::WriteOnly)) {
        qDebug() << "Cannot open file for writing:" << filename;
        return false;
    }
    
    QDataStream stream(&file);
    stream.setByteOrder(QDataStream::LittleEndian);
    
    writeWavHeader(stream, audioData.size());
    stream.writeRawData(audioData.constData(), audioData.size());
    
    file.close();
    qDebug() << "WAV file saved:" << filename << "size:" << audioData.size() << "bytes";
    return true;
}

bool SimpleWavWriter::saveToMusicFile(const QString &filename)
{
    QFile file(filename);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        qDebug() << "Cannot open music file for writing:" << filename;
        return false;
    }
    
    QTextStream stream(&file);
    stream.setCodec("UTF-8");
    
    // File header
    stream << "; Music composition generated by Yamitracker\n";
    stream << "; Format: Pently-style with tracks\n";
    stream << "; Creation time: " << QDateTime::currentDateTime().toString("yyyy-MM-dd hh:mm:ss") << "\n";
    stream << "; Number of tracks: ";
    
    int activeTracks = 0;
    for (int i = 0; i < MAX_TRACKS; i++) {
        if (!m_tracks[i].events.isEmpty()) {
            activeTracks++;
        }
    }
    stream << activeTracks << "\n\n";
    
    stream << ".include \"pentlyseq.inc\"\n";
    stream << ".segment \"SPCIMAGE\"\n\n";
    
    // Instrument table (using standard Pently instruments)
    stream << "; Instrument table\n";
    stream << "music_inst_table:\n";
    stream << "  ;    name         lv  rv frq smp att dec sus lvl\n";
    stream << "  INST KICK,        11, 10,  3,  6, 31, 17,  0,  8\n";
    stream << "  INST SNARE,       10, 15,  3,  7, 31, 17,  0,  8\n";
    stream << "  INST HAT,          3,  5,  3,  5, 31, 17,  0,  8\n";
    stream << "  INST PLING_8,      3, 10,  1,  0, 31, 19, 15,  2\n";
    stream << "  INST PLING_4,      7,  7,  1,  1, 31, 19, 15,  2\n";
    stream << "  INST PLING_2,      9,  6,  1,  2, 31, 17, 15,  2\n";
    stream << "  INST BASSGUITAR,  12, 12,  1,  4, 31, 17, 15,  8\n";
    stream << "  INST BASSCLAR,    12, 12,  1,  2, 21, 21, 27,  4\n";
    stream << "  INST HORNBLAT,     3,  9,  1,  0, 21, 21, 27,  4\n";
    stream << "  INST XYLSHORT,    10,  6,  1,  2, 31, 23, 20,  2\n";
    stream << "  INST XYLMED,      10,  6,  1,  2, 31, 19, 17,  2\n\n";
    
    // Generate patterns for each track
    stream << "pently_patterns:\n";
    
    QMap<int, QVector<QVector<WavEvent>>> trackPatterns;
    int totalPatternCount = 0;
    
    // First collect all patterns from all tracks
    for (int track = 0; track < MAX_TRACKS; track++) {
        if (m_tracks[track].events.isEmpty()) continue;
        
        // Group events by time to create patterns (1 second groups)
        QVector<QVector<WavEvent>> patternGroups = groupEventsByTime(track, 1.0);
        trackPatterns[track] = patternGroups;
        totalPatternCount += patternGroups.size();
    }
    
    // Now write all patterns with proper indexing
    int currentPatternIndex = 0;
    QMap<int, QMap<int, int>> trackPatternIndices; // track -> group index -> pattern index
    
    for (int track = 0; track < MAX_TRACKS; track++) {
        if (!trackPatterns.contains(track)) continue;
        
        const QVector<QVector<WavEvent>>& patterns = trackPatterns[track];
        
        for (int groupIdx = 0; groupIdx < patterns.size(); groupIdx++) {
            const QVector<WavEvent>& patternEvents = patterns[groupIdx];
            
            stream << QString("PPDAT_track%1_pattern%2:\n").arg(track).arg(groupIdx);
            
            // Determine instrument for this track
            QString instrumentName = getInstrumentMacroName(m_tracks[track].instrument);
            
            // Check if pattern has different instruments
            bool hasDifferentInstruments = false;
            int firstInstrument = patternEvents.isEmpty() ? 0 : patternEvents[0].instrument;
            for (const auto& event : patternEvents) {
                if (event.instrument != firstInstrument && !event.isPause) {
                    hasDifferentInstruments = true;
                    break;
                }
            }
            
            // Always add instrument command at start of pattern
            stream << QString("  .byt INSTRUMENT, %1\n").arg(instrumentName);
            
            // Add notes
            for (const auto& event : patternEvents) {
                QString noteCmd = getNoteCommand(event, false);
                if (!noteCmd.isEmpty()) {
                    stream << "  .byt " << noteCmd << "\n";
                }
            }
            
            stream << "  .byt PATEND\n";
            
            // Store the pattern index for this track and group
            if (!trackPatternIndices.contains(track)) {
                trackPatternIndices[track] = QMap<int, int>();
            }
            trackPatternIndices[track][groupIdx] = currentPatternIndex;
            currentPatternIndex++;
        }
    }
    
    // Generate song data
    stream << "\npently_songs:\n";
    stream << ".addr  PSDAT_composition\n\n";
    
    stream << "; Main composition\n";
    stream << "PSDAT_composition:\n";
    stream << "  setTempo 300\n\n";
    
    // Calculate maximum number of pattern groups across all tracks
    int maxGroups = 0;
    for (int track = 0; track < MAX_TRACKS; track++) {
        if (trackPatterns.contains(track)) {
            maxGroups = qMax(maxGroups, trackPatterns[track].size());
        }
    }
    
    // Play patterns in parallel (all tracks simultaneously)
    for (int groupIdx = 0; groupIdx < maxGroups; groupIdx++) {
        bool anyTrackHasPattern = false;
        
        // Start patterns for all tracks that have this group
        for (int track = 0; track < MAX_TRACKS; track++) {
            if (trackPatterns.contains(track) && groupIdx < trackPatterns[track].size()) {
                QString instrumentName = getInstrumentMacroName(m_tracks[track].instrument);
                int patternIndex = trackPatternIndices[track][groupIdx];
                
                stream << QString("  playPat %1, %2, 0, %3\n")
                          .arg(track)  // Channel
                          .arg(patternIndex)  // Pattern index
                          .arg(instrumentName);  // Instrument
                anyTrackHasPattern = true;
            }
        }
        
        if (anyTrackHasPattern) {
            // Wait for the pattern to complete
            stream << QString("  waitRows 16\n\n");
        }
    }
    
    stream << "\n  ; Composition end\n";
    stream << "  waitRows 32\n";
    stream << "  fine\n";
    
    file.close();
    qDebug() << "Music file saved in Pently format:" << filename;
    return true;
}

void SimpleWavWriter::addNote(int track, double time, int note, int velocity, double duration, int instrument)
{
    if (track < 0 || track >= MAX_TRACKS) return;
    
    // Adjust note for Pently format (limit range)
    int adjustedNote = note;
    if (adjustedNote < 24) adjustedNote = 24; // C2
    if (adjustedNote > 84) adjustedNote = 84; // C6
    
    WavEvent event;
    event.track = track;
    event.time = time;
    event.note = adjustedNote;
    event.velocity = velocity;
    event.duration = duration * m_sampleRate;
    event.instrument = instrument;
    event.isPause = false;
    
    m_tracks[track].events.append(event);
    
    // Sort events by time
    std::sort(m_tracks[track].events.begin(), m_tracks[track].events.end(),
        [](const WavEvent& a, const WavEvent& b) {
            return a.time < b.time;
        });
    
    // Clear cached audio data
    m_tracks[track].audioData.clear();
    
    emit trackUpdated(track);
}

void SimpleWavWriter::addSilence(int track, double duration)
{
    if (track < 0 || track >= MAX_TRACKS) return;
    
    // Find time of last event
    double lastTime = 0;
    if (!m_tracks[track].events.isEmpty()) {
        const WavEvent& lastEvent = m_tracks[track].events.last();
        lastTime = lastEvent.time + (double)lastEvent.duration / m_sampleRate;
    }
    
    WavEvent event;
    event.track = track;
    event.time = lastTime;
    event.note = 0;
    event.velocity = 0;
    event.duration = duration * m_sampleRate;
    event.instrument = 0;
    event.isPause = true;
    
    m_tracks[track].events.append(event);
    m_tracks[track].audioData.clear();
    
    emit trackUpdated(track);
}

void SimpleWavWriter::addPause(int track, double duration)
{
    addSilence(track, duration);
}

void SimpleWavWriter::clearTrack(int track)
{
    if (track < 0 || track >= MAX_TRACKS) return;
    
    m_tracks[track].events.clear();
    m_tracks[track].audioData.clear();
    
    emit trackUpdated(track);
}

void SimpleWavWriter::clearAllTracks()
{
    for (int i = 0; i < MAX_TRACKS; i++) {
        m_tracks[i].events.clear();
        m_tracks[i].audioData.clear();
        emit trackUpdated(i);
    }
}

void SimpleWavWriter::mergeTrack(int fromTrack, int toTrack)
{
    if (fromTrack < 0 || fromTrack >= MAX_TRACKS || 
        toTrack < 0 || toTrack >= MAX_TRACKS || 
        fromTrack == toTrack) {
        return;
    }
    
    for (const auto& event : m_tracks[fromTrack].events) {
        m_tracks[toTrack].events.append(event);
    }
    
    // Sort events by time
    std::sort(m_tracks[toTrack].events.begin(), m_tracks[toTrack].events.end(),
        [](const WavEvent& a, const WavEvent& b) {
            return a.time < b.time;
        });
    
    m_tracks[toTrack].audioData.clear();
    m_tracks[fromTrack].events.clear();
    m_tracks[fromTrack].audioData.clear();
    
    emit trackUpdated(fromTrack);
    emit trackUpdated(toTrack);
}

void SimpleWavWriter::copyTrack(int fromTrack, int toTrack)
{
    if (fromTrack < 0 || fromTrack >= MAX_TRACKS || 
        toTrack < 0 || toTrack >= MAX_TRACKS || 
        fromTrack == toTrack) {
        return;
    }
    
    m_tracks[toTrack].events = m_tracks[fromTrack].events;
    m_tracks[toTrack].audioData.clear();
    
    emit trackUpdated(toTrack);
}

