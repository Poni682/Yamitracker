void SimpleWavWriter::writeWavHeader(QDataStream &stream, quint32 dataSize)
{
    // RIFF header
    stream.writeRawData("RIFF", 4);
    quint32 chunkSize = 36 + dataSize;
    stream << chunkSize;
    stream.writeRawData("WAVE", 4);
    
    // fmt chunk
    stream.writeRawData("fmt ", 4);
    quint32 subchunk1Size = 16;
    stream << subchunk1Size;
    
    quint16 audioFormat = 1; // PCM
    stream << audioFormat;
    
    quint16 numChannels = 1; // Mono
    stream << numChannels;
    
    quint32 sampleRate = m_sampleRate;
    stream << sampleRate;
    
    quint32 byteRate = sampleRate * numChannels * 2; // 16-bit = 2 bytes
    stream << byteRate;
    
    quint16 blockAlign = numChannels * 2;
    stream << blockAlign;
    
    quint16 bitsPerSample = 16;
    stream << bitsPerSample;
    
    // data chunk
    stream.writeRawData("data", 4);
    stream << dataSize;
}

QByteArray SimpleWavWriter::generateTrackAudio(int track, bool includeEffects)
{
    if (track < 0 || track >= MAX_TRACKS || m_tracks[track].events.isEmpty()) {
        return QByteArray();
    }
    
    QByteArray audioData;
    QDataStream stream(&audioData, QIODevice::WriteOnly);
    stream.setByteOrder(QDataStream::LittleEndian);
    
    double trackDuration = getTrackDuration(track);
    int totalSamples = static_cast<int>(trackDuration * m_sampleRate);
    
    // Create buffer for samples
    QVector<double> sampleBuffer(totalSamples, 0.0);
    
    // Generate each event
    for (const auto& event : m_tracks[track].events) {
        if (event.isPause) continue;
        
        double frequency = noteToFrequency(event.note);
        int startSample = static_cast<int>(event.time * m_sampleRate);
        int endSample = startSample + event.duration;
        
        // Determine gain for bass notes
        double volumeMultiplier = 1.0;
        if (event.instrument >= 28 && event.instrument <= 40) {
            volumeMultiplier = m_bassVolumeMultiplier;
        }
        
        // Consider track volume
        volumeMultiplier *= m_tracks[track].volume * m_masterVolume;
        
        double baseAmplitude = (event.velocity / 127.0) * 0.7 * volumeMultiplier;
        
        // Envelope parameters for this instrument
        double attack = getAttackForInstrument(event.instrument);
        double decay = getDecayForInstrument(event.instrument);
        double sustain = getSustainForInstrument(event.instrument);
        double release = getReleaseForInstrument(event.instrument);
        
        // Generate note
        for (int i = 0; i < event.duration && (startSample + i) < totalSamples; i++) {
            double noteTime = static_cast<double>(i) / m_sampleRate;
            double noteDuration = static_cast<double>(event.duration) / m_sampleRate;
            
            // ADSR envelope
            double envelope = 1.0;
            if (includeEffects) {
                envelope = adsrEnvelope(noteTime, noteDuration, attack, decay, sustain, release);
            }
            
            // Amplitude with envelope
            double amplitude = baseAmplitude * envelope;
            
            // Limit amplitude to avoid clipping
            if (amplitude > 1.0) amplitude = 1.0;
            
            // Generate wave
            double t = event.time + noteTime;
            double sampleValue = 0.0;
            
            if (includeEffects) {
                short sample = generateWaveform(t, frequency, amplitude, event.instrument);
                sampleValue = static_cast<double>(sample) / 32767.0;
            } else {
                // For preview use simple sine
                sampleValue = sin(2.0 * M_PI * frequency * t) * amplitude;
            }
            
            // Add to buffer
            sampleBuffer[startSample + i] += sampleValue;
        }
    }
    
    // Convert buffer to 16-bit samples
    for (double sampleValue : sampleBuffer) {
        // Limit value to avoid clipping
        if (sampleValue > 1.0) sampleValue = 1.0;
        if (sampleValue < -1.0) sampleValue = -1.0;
        
        short sample = static_cast<short>(sampleValue * 32767.0);
        stream << sample;
    }
    
    return audioData;
}

void SimpleWavWriter::generateAllTracksAudio()
{
    for (int track = 0; track < MAX_TRACKS; track++) {
        if (!m_tracks[track].events.isEmpty()) {
            m_tracks[track].audioData = generateTrackAudio(track, true);
            emit audioDataReady(track, m_tracks[track].audioData);
        }
    }
}

double SimpleWavWriter::adsrEnvelope(double noteTime, double noteDuration, 
                                   double attack, double decay, 
                                   double sustain, double release)
{
    double envelope = 1.0;
    
    if (noteTime < attack) {
        // Attack
        envelope = noteTime / attack;
    } else if (noteTime < attack + decay) {
        // Decay
        envelope = 1.0 - ((noteTime - attack) / decay) * (1.0 - sustain);
    } else if (noteTime < noteDuration - release) {
        // Sustain
        envelope = sustain;
    } else if (noteTime < noteDuration) {
        // Release
        double releaseTime = noteTime - (noteDuration - release);
        envelope = sustain * (1.0 - releaseTime / release);
    } else {
        // After release
        envelope = 0.0;
    }
    
    return envelope;
}

double SimpleWavWriter::sineWave(double phase)
{
    return sin(2.0 * M_PI * phase);
}

double SimpleWavWriter::squareWave(double phase)
{
    return sin(2.0 * M_PI * phase) > 0 ? 0.7 : -0.7;
}

double SimpleWavWriter::sawtoothWave(double phase)
{
    return 2.0 * (phase - floor(phase + 0.5));
}

double SimpleWavWriter::triangleWave(double phase)
{
    double x = 2.0 * (phase - floor(phase + 0.5));
    return 2.0 * fabs(x) - 1.0;
}

double SimpleWavWriter::noiseWave()
{
    return (2.0 * rand() / RAND_MAX) - 1.0;
}

double SimpleWavWriter::lowPassFilter(double input, double &prev, double cutoff)
{
    double RC = 1.0 / (2.0 * M_PI * cutoff);
    double dt = 1.0 / m_sampleRate;
    double alpha = dt / (RC + dt);
    double output = prev + alpha * (input - prev);
    prev = output;
    return output;
}

double SimpleWavWriter::highPassFilter(double input, double &prevInput, double &prevOutput, double cutoff)
{
    double RC = 1.0 / (2.0 * M_PI * cutoff);
    double dt = 1.0 / m_sampleRate;
    double alpha = RC / (RC + dt);
    double output = alpha * (prevOutput + input - prevInput);
    prevInput = input;
    prevOutput = output;
    return output;
}

double SimpleWavWriter::noteToFrequency(int note)
{
    return 440.0 * pow(2.0, (note - 69) / 12.0);
}

int SimpleWavWriter::frequencyToNote(double frequency)
{
    return static_cast<int>(69 + 12 * log2(frequency / 440.0));
}

QString SimpleWavWriter::noteNumberToName(int note)
{
    static const QString noteNames[] = {
        "C", "CS", "D", "DS", "E", "F", "FS", "G", "GS", "A", "AS", "B"
    };
    
    int octave = note / 12;
    int noteIndex = note % 12;
    
    QString name = noteNames[noteIndex];
    
    // Add octave designation for Pently format
    if (octave >= 5) {
        name += "HH"; // High high
    } else if (octave == 4) {
        name += "H";  // High
    } else if (octave == 3) {
        // First octave - no suffix
    } else if (octave == 2) {
        name += "L";  // Low
    } else if (octave <= 1) {
        name += "LL"; // Low low
    }
    
    return name;
}

QString SimpleWavWriter::getDurationSymbol(int durationSamples)
{
    double durationSeconds = static_cast<double>(durationSamples) / m_sampleRate;
    
    // Convert to note durations for Pently
    if (durationSeconds >= 2.0) return "1";
    else if (durationSeconds >= 1.5) return "D2";
    else if (durationSeconds >= 1.0) return "2";
    else if (durationSeconds >= 0.75) return "D4";
    else if (durationSeconds >= 0.5) return "4";
    else if (durationSeconds >= 0.375) return "D8";
    else if (durationSeconds >= 0.25) return "8";
    else if (durationSeconds >= 0.1875) return "D16";
    else if (durationSeconds >= 0.125) return "16";
    else if (durationSeconds >= 0.09375) return "D32";
    else return "32";
}

