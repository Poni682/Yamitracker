double SimpleWavWriter::getTotalDuration() const
{
    double maxDuration = 0;
    
    for (int track = 0; track < MAX_TRACKS; track++) {
        double trackDuration = getTrackDuration(track);
        if (trackDuration > maxDuration) {
            maxDuration = trackDuration;
        }
    }
    
    return maxDuration;
}

